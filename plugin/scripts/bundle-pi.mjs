// Bundles pi-binding and advisor-core from their TypeScript sources into one self-contained pi
// extension file. pi provides `typebox` and its own packages to extensions at run time, so those
// stay imports; everything else is inlined. Used by `pnpm build` and by agents/pi/Dockerfile.
// Usage: node scripts/bundle-pi.mjs [OUTFILE]   (default pi-binding/dist/lso-advisor.js)
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = process.argv[2] ?? join(root, "pi-binding", "dist", "lso-advisor.js");

await build({
  entryPoints: [join(root, "pi-binding", "src", "index.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  alias: { "@llm-second-opinion/advisor-core": join(root, "advisor-core", "src", "index.ts") },
  external: ["typebox", "@earendil-works/*"],
  banner: { js: "// llm_second_opinion advisor extension for pi. Generated by plugin/scripts/bundle-pi.mjs." },
  logLevel: "warning",
});
console.log(`wrote ${outfile}`);
